/**
 * Generate generated/nova-tokens.css from acorn-web-components' published token
 * map + our flag-off/alias config (token-map.mjs).
 *
 *   :root                     flag OFF — today's values (pixel-identical)
 *   [data-theme="nova"]       flag ON  — Acorn's tokens (light-dark, so light/
 *                                        dark follow color-scheme) + our palette
 *                                        names aliased onto Acorn's ramp
 *
 * Acorn tokens source: the `acorn-web-components/tokens` export (a typed map).
 * We re-emit it scoped under the flag rather than importing its :root tokens.css,
 * so the refresh can be toggled/rolled back at runtime. (If Acorn ships a
 * selector-scoped build, this re-emit goes away — see README.)
 *
 * Run: `nx build shared-design-tokens`
 *   bootstrap from the cloned repo before the dep is installed:
 *     ACORN_TOKENS=../acorn-web-components/src/generated/tokens.ts node src/generate.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import {
  LEGACY_PALETTE,
  LEGACY_SEMANTICS,
  primitiveAliases,
} from './token-map.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '..', 'generated', 'nova-tokens.css');

// Acorn ships the tokens as a module of `'--name': "value"` pairs (tokens.ts /
// tokens.js). Read it as text and extract the pairs — one path for the installed
// package and the cloned-repo bootstrap alike.
const tokensPath = process.env.ACORN_TOKENS
  ? resolve(process.cwd(), process.env.ACORN_TOKENS)
  : createRequire(import.meta.url).resolve('acorn-web-components/tokens');
const acorn = Object.fromEntries(
  [...readFileSync(tokensPath, 'utf8').matchAll(/'(--[\w-]+)':\s*"([^"]*)"/g)].map(
    (m) => [m[1], m[2]]
  )
);
if (!Object.keys(acorn).length) throw new Error(`No tokens parsed from ${tokensPath}`);

const decls = (obj) =>
  Object.entries(obj)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join('\n');

const legacyPrimitives = {};
for (const [name, val] of Object.entries(LEGACY_PALETTE)) {
  if (typeof val === 'string') legacyPrimitives[`--color-${name}`] = val;
  else for (const [shade, hex] of Object.entries(val)) legacyPrimitives[`--color-${name}-${shade}`] = hex;
}

const css = `/* This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at http://mozilla.org/MPL/2.0/. */

/* GENERATED by libs/shared/design-tokens/src/generate.mjs — DO NOT EDIT.
 * Source: acorn-web-components token map. Regenerate: nx build shared-design-tokens */

/* Flag OFF — today's values (pixel-identical to current). */
:root {
${decls(legacyPrimitives)}
${decls(LEGACY_SEMANTICS)}
}

/* Flag ON — Acorn tokens (light/dark via color-scheme) + palette aliases. */
[data-theme="nova"] {
  color-scheme: light dark;
${decls(primitiveAliases())}
${decls(acorn)}
}
`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, css);
console.log(
  `Wrote ${OUT}\n  acorn tokens: ${Object.keys(acorn).length}, aliases: ${Object.keys(primitiveAliases()).length}, legacy: ${Object.keys(legacyPrimitives).length + Object.keys(LEGACY_SEMANTICS).length}`
);
